/** 技术名词黑名单：提示词里出现任意一个都不符合「只描述功能」的约定。 */
export const TECH_TERMS: readonly string[] = [
  'html', 'css', 'javascript', 'java script', 'typescript', 'vue', 'react', 'jquery',
  'flexbox', 'grid 布局', 'localstorage', 'sessionstorage', 'indexeddb', 'promise',
  'async', 'await', 'api', 'dom', 'json', 'aria-', 'role=', 'settimeout', 'try/catch',
  'sass', 'less', 'tailwind', 'bootstrap', 'npm', 'webpack', 'vite', 'babel',
  '框架', '组件库', '第三方库', '样式表', '脚本', '源码', '代码', '接口',
  '变量', '数组', '函数', '样式选择器', '兄弟选择器', '伪类', '属性', '标签名',
  '单文件', '原生', '类库'
]

/** 返回一段文本里命中的技术名词（去重、保持黑名单顺序）。 */
export function findTechnicalTerms(text: string): string[] {
  const lower = text.toLowerCase()
  const hits: string[] = []
  for (const term of TECH_TERMS) {
    if (lower.includes(term) && !hits.includes(term)) hits.push(term)
  }
  // 尺寸字面量（30px / 12px）也属于实现细节，单独识别
  if (/\d+\s*px\b/i.test(text)) hits.push('px 尺寸')
  return hits
}

export interface FrontendPromptFilter {
  keyword?: string
  category?: string
}

/** 分类 + 关键字叠加筛选（标题 / 摘要 / 提示词全文都参与匹配）。 */
export function filterFrontendPrompts(
  items: readonly FrontendPromptItem[],
  { keyword = '', category = '' }: FrontendPromptFilter = {}
): FrontendPromptItem[] {
  const q = keyword.trim().toLowerCase()
  return items.filter(item => {
    if (category && item.category !== category) return false
    if (!q) return true
    return [item.title, item.summary, item.prompt, item.id].some(s => s.toLowerCase().includes(q))
  })
}

export function getFrontendPrompt(id: string): FrontendPromptItem | undefined {
  return FRONTEND_PROMPTS.find(item => item.id === id)
}

/** 各分类的卡片数（含「全部」总数），供筛选标签显示计数。 */
export function countFrontendPrompts(items: readonly FrontendPromptItem[]): Record<string, number> {
  const out: Record<string, number> = { all: items.length }
  for (const item of items) out[item.category] = (out[item.category] ?? 0) + 1
  return out
}
